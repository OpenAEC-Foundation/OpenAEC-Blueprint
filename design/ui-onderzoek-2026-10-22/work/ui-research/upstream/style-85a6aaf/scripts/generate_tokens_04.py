#!/usr/bin/env python3
"""Generate the UI 0.4 design tokens for Rust and CSS.

Source: design/ontwerp-0.4/tokens-0.4.json (the single source of truth).
Writes:
  crates/openaec-ui/src/design/tokens.rs   Rust module `openaec_ui::design::tokens`
  web/openaec-tokens.css            CSS custom properties for web apps

Run with --check to verify that both files are up to date without writing.
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "design/ontwerp-0.4/tokens-0.4.json"
RUST = ROOT / "crates/openaec-ui/src/design/tokens.rs"
CSS = ROOT / "web/openaec-tokens.css"
sys.path.insert(0, str(Path(__file__).resolve().parent))
from check_tokens_04 import evaluate, luminance  # noqa: E402

VARIANTS = {"light": "Light", "dark": "Dark", "blueprint": "Blueprint",
            "high-contrast-dark": "HighContrastDark", "high-contrast-light": "HighContrastLight"}


def snake(key):
    s = key.replace("-", "_").upper()
    return {"2XL": "XXL"}.get(s, s)


def field(key):
    return key.replace("-", "_")


def rgba(value):
    """Parse #RRGGBB or rgba(r,g,b,a) into four floats in 0..1."""
    value = value.strip()
    if value.startswith("#"):
        h = value[1:]
        return tuple(int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)) + (1.0,)
    n = [float(x) for x in re.findall(r"[\d.]+", value)]
    return (n[0] / 255, n[1] / 255, n[2] / 255, n[3] if len(n) == 4 else 1.0)


def rust_color(value):
    return "Color { r: %.9f, g: %.9f, b: %.9f, a: %.9f }" % rgba(value)


def shadow_layers(value):
    """Split a CSS box-shadow into layers: (inset, x, y, blur, spread, color)."""
    if value.strip() == "none":
        return []
    layers = []
    for part in re.split(r",(?![^(]*\))", value):
        part = part.strip()
        inset = part.startswith("inset")
        part = part.removeprefix("inset").strip()
        color = re.search(r"(rgba?\([^)]*\)|#[0-9A-Fa-f]{6})", part).group(1)
        nums = [float(x) for x in re.findall(r"-?[\d.]+(?=px|\s|$)", part.replace(color, ""))]
        nums += [0.0] * (4 - len(nums))
        layers.append((inset, *nums[:4], color))
    return layers


def rust_shadow(value):
    items = [f"ShadowLayer {{ inset: {str(i).lower()}, x: {x:.1f}, y: {y:.1f}, blur: {b:.1f}, spread: {s:.1f}, color: {rust_color(c)} }}"
             for i, x, y, b, s, c in shadow_layers(value)]
    return "&[" + ", ".join(items) + "]"


def build_rust(t):
    themes = t["themes"]
    keys = list(next(iter(themes.values()))["color"])
    ws = t["workspace-setting"]["options"]
    sb = t["statusbar-setting"]["options"]
    o = []
    w = o.append
    w("//! UI 0.4 design tokens: themes, colours, type, spacing, radii and shell sizes.")
    w("//!")
    w("//! Generated by `scripts/generate_tokens_04.py` from")
    w(f"//! `design/ontwerp-0.4/tokens-0.4.json` (version {t['meta']['version']}). Do not edit by hand;")
    w("//! change the JSON and run the generator. This module is the start of library 0.4");
    w("//! and is independent of the prototype theme in [`crate::theme`].")
    w("use iced::{Color, Shadow, Vector};")
    w("use serde::{Deserialize, Serialize};")
    w("")
    w(f'pub const VERSION: &str = "{t["meta"]["version"]}";')
    w("")
    w("/// The five UI 0.4 themes.")
    w("#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Hash, Serialize, Deserialize)]")
    w('#[serde(rename_all = "kebab-case")]')
    w("pub enum ThemeId {")
    for i, v in enumerate(VARIANTS.values()):
        w(("    #[default]\n" if i == 0 else "") + f"    {v},")
    w("}")
    w("")
    w("impl ThemeId {")
    w("    pub const ALL: [Self; %d] = [%s];" % (len(VARIANTS), ", ".join(f"Self::{v}" for v in VARIANTS.values())))
    w("    pub fn tokens(self) -> &'static ThemeTokens {")
    w("        match self {")
    for k, v in VARIANTS.items():
        w(f"            Self::{v} => &{snake(k)},")
    w("        }")
    w("    }")
    w("    /// Stable key, as used in settings files and the CSS attribute `data-oa-theme`.")
    w("    pub fn key(self) -> &'static str {")
    w("        self.tokens().key")
    w("    }")
    w("    /// Dutch display name.")
    w("    pub fn name(self) -> &'static str {")
    w("        self.tokens().name")
    w("    }")
    w("    pub fn from_key(key: &str) -> Option<Self> {")
    w("        Self::ALL.into_iter().find(|t| t.key() == key)")
    w("    }")
    w("    /// An iced theme whose palette follows these tokens.")
    w("    pub fn iced(self) -> iced::Theme {")
    w("        let c = &self.tokens().color;")
    w("        iced::Theme::custom(self.name().to_string(), iced::theme::Palette {")
    w("            background: c.panel, text: c.text, primary: c.accent, success: c.success, danger: c.error,")
    w("        })")
    w("    }")
    w("}")
    w("")
    w("impl std::fmt::Display for ThemeId {")
    w("    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {")
    w("        f.write_str(self.name())")
    w("    }")
    w("}")
    w("")
    w("/// Colour roles of one theme. All colours are opaque.")
    w("#[derive(Debug, Clone, Copy, PartialEq)]")
    w("pub struct Palette {")
    for k in keys:
        w(f"    pub {field(k)}: Color,")
    w("}")
    w("")
    w("/// One layer of a CSS-style box shadow. Layers with spread and no blur are rings.")
    w("#[derive(Debug, Clone, Copy, PartialEq)]")
    w("pub struct ShadowLayer {")
    w("    pub inset: bool,")
    w("    pub x: f32,")
    w("    pub y: f32,")
    w("    pub blur: f32,")
    w("    pub spread: f32,")
    w("    pub color: Color,")
    w("}")
    w("")
    w("impl ShadowLayer {")
    w("    /// The layer as an iced shadow. iced draws no spread or inset, so callers draw rings as borders.")
    w("    pub fn iced(&self) -> Shadow {")
    w("        Shadow { color: self.color, offset: Vector::new(self.x, self.y), blur_radius: self.blur }")
    w("    }")
    w("}")
    w("")
    w("#[derive(Debug, Clone, Copy, PartialEq)]")
    w("pub struct Shadows {")
    w("    pub panel: &'static [ShadowLayer],")
    w("    pub popup: &'static [ShadowLayer],")
    w("    pub dialog: &'static [ShadowLayer],")
    w("}")
    w("")
    w("impl Shadows {")
    w("    /// The first outer blurred layer, which iced can draw directly.")
    w("    pub fn drop_shadow(layers: &[ShadowLayer]) -> Option<Shadow> {")
    w("        layers.iter().find(|l| !l.inset && l.blur > 0.0).map(ShadowLayer::iced)")
    w("    }")
    w("}")
    w("")
    w("/// Everything one theme defines.")
    w("#[derive(Debug, Clone, Copy, PartialEq)]")
    w("pub struct ThemeTokens {")
    w("    pub key: &'static str,")
    w("    pub name: &'static str,")
    w("    pub dark: bool,")
    w("    pub high_contrast: bool,")
    w("    /// Selection is an outline instead of a tint (High contrast).")
    w("    pub selection_outline: bool,")
    w("    /// Disabled controls get a dashed border instead of fading (High contrast).")
    w("    pub disabled_dashed: bool,")
    w("    pub color: Palette,")
    w("    pub shadow: Shadows,")
    w("    pub overlay: Color,")
    w("}")
    w("")
    for k, th in themes.items():
        c = th["color"]
        w(f"pub const {snake(k)}: ThemeTokens = ThemeTokens {{")
        w(f'    key: "{k}",')
        w(f'    name: "{th["name"]}",')
        w(f"    dark: {str(th['kind'] == 'dark').lower()},")
        w(f"    high_contrast: {str(bool(th.get('high-contrast'))).lower()},")
        w(f"    selection_outline: {str(th['selection-style'] == 'outline').lower()},")
        w(f"    disabled_dashed: {str(th['disabled-style'] == 'dashed').lower()},")
        w("    color: Palette {")
        for key in keys:
            w(f"        {field(key)}: {rust_color(c[key])},")
        w("    },")
        w("    shadow: Shadows {")
        for s in ("panel", "popup", "dialog"):
            w(f"        {s}: {rust_shadow(th['shadow'][s])},")
        w("    },")
        w(f"    overlay: {rust_color(th['overlay'])},")
        w("};")
        w("")
    # Settings
    w("/// User setting Werkruimte. The default follows the theme; High contrast ignores it.")
    w("#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Hash, Serialize, Deserialize)]")
    w('#[serde(rename_all = "kebab-case")]')
    w("pub enum WorkspaceSetting {")
    w("    #[default]")
    w("    Theme,")
    w("    Light,")
    w("    Dark,")
    w("}")
    w("")
    w("impl WorkspaceSetting {")
    w("    pub const ALL: [Self; 3] = [Self::Theme, Self::Light, Self::Dark];")
    w("    pub fn name(self) -> &'static str {")
    w(f'        match self {{ Self::Theme => "{ws["theme"]["name"]}", Self::Light => "{ws["light"]["name"]}", Self::Dark => "{ws["dark"]["name"]}" }}')
    w("    }")
    w("}")
    w("")
    w("impl std::fmt::Display for WorkspaceSetting {")
    w("    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {")
    w("        f.write_str(self.name())")
    w("    }")
    w("}")
    w("")
    w("/// User setting Statusbalk. The default follows the theme; High contrast ignores it.")
    w("#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Hash, Serialize, Deserialize)]")
    w('#[serde(rename_all = "kebab-case")]')
    w("pub enum StatusbarSetting {")
    w("    #[default]")
    w("    Theme,")
    w("    Dark,")
    w("}")
    w("")
    w("impl StatusbarSetting {")
    w("    pub const ALL: [Self; 2] = [Self::Theme, Self::Dark];")
    w("    pub fn name(self) -> &'static str {")
    w(f'        match self {{ Self::Theme => "{sb["theme"]["name"]}", Self::Dark => "{sb["dark"]["name"]}" }}')
    w("    }")
    w("}")
    w("")
    w("impl std::fmt::Display for StatusbarSetting {")
    w("    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {")
    w("        f.write_str(self.name())")
    w("    }")
    w("}")
    w("")
    w("impl ThemeTokens {")
    w("    /// The palette after the Werkruimte and Statusbalk settings.")
    w("    ///")
    w("    /// A workspace of the other kind than the theme also takes that kind's")
    w("    /// `accent_text`, so accent text in the workspace keeps its contrast.")
    w("    pub fn palette(&self, workspace: WorkspaceSetting, statusbar: StatusbarSetting) -> Palette {")
    w("        let mut c = self.color;")
    w("        if self.high_contrast {")
    w("            return c;")
    w("        }")
    w("        match workspace {")
    w("            WorkspaceSetting::Theme => {}")
    w(f"            WorkspaceSetting::Light => {{ c.workspace = {rust_color(ws['light']['workspace'])}; c.workspace_text = {rust_color(ws['light']['workspace-text'])}; }}")
    w(f"            WorkspaceSetting::Dark => {{ c.workspace = {rust_color(ws['dark']['workspace'])}; c.workspace_text = {rust_color(ws['dark']['workspace-text'])}; }}")
    w("        }")
    w("        if let StatusbarSetting::Dark = statusbar {")
    w(f"            c.statusbar = {rust_color(sb['dark']['statusbar'])};")
    w(f"            c.statusbar_text = {rust_color(sb['dark']['statusbar-text'])};")
    w("        }")
    w("        c")
    w("    }")
    w("")
    w("    /// Accent text colour inside the workspace for a Werkruimte setting.")
    w("    pub fn workspace_accent_text(&self, workspace: WorkspaceSetting) -> Color {")
    w("        match workspace {")
    w("            _ if self.high_contrast => self.color.accent_text,")
    w("            WorkspaceSetting::Light if self.dark => LIGHT.color.accent_text,")
    w("            WorkspaceSetting::Dark if !self.dark => DARK.color.accent_text,")
    w("            _ => self.color.accent_text,")
    w("        }")
    w("    }")
    w("}")
    w("")
    # Scalars
    f = t["font"]
    w("/// Type: families, sizes in pixels, weights and letter spacing in em.")
    w("pub mod font {")
    for k, v in f["family"].items():
        w(f'    pub const {snake(k)}: &str = "{v}";')
    for k, v in f["size"].items():
        w(f"    pub const SIZE_{snake(k)}: f32 = {float(v):.1f};")
    for k, v in f["weight"].items():
        w(f"    pub const WEIGHT_{snake(k)}: u16 = {v};")
    for k, v in f["letter-spacing"].items():
        w(f"    pub const LETTER_SPACING_{snake(k)}: f32 = {float(v.removesuffix('em'))};")
    w("    /// Mono labels are uppercase JetBrains Mono at the label size.")
    w("    pub const MONO_LABEL_UPPERCASE: bool = %s;" % str(f["mono-label"]["transform"] == "uppercase").lower())
    w("}")
    w("")
    for mod, doc in (("space", "Spacing on the 4 px grid, in pixels."), ("radius", "Corner radii in pixels (variant D)."),
                     ("shell", "Fixed shell sizes in pixels.")):
        w(f"/// {doc}")
        w(f"pub mod {mod} {{")
        for k, v in t[mod].items():
            w(f"    pub const {snake(k)}: f32 = {float(v):.1f};")
        w("}")
        w("")
    w("/// Brand colours of the OpenAEC website.")
    w("pub mod brand {")
    w("    use iced::Color;")
    for k, v in t["brand"].items():
        w(f"    pub const {snake(k)}: Color = {rust_color(v)};")
    w("}")
    w("")
    w("#[cfg(test)]")
    w("mod tests {")
    w("    use super::*;")
    w("")
    w("    fn luminance(c: Color) -> f32 {")
    w("        let ch = |v: f32| if v <= 0.04045 { v / 12.92 } else { ((v + 0.055) / 1.055).powf(2.4) };")
    w("        0.2126 * ch(c.r) + 0.7152 * ch(c.g) + 0.0722 * ch(c.b)")
    w("    }")
    w("")
    w("    fn contrast(a: Color, b: Color) -> f32 {")
    w("        let (x, y) = (luminance(a), luminance(b));")
    w("        (x.max(y) + 0.05) / (x.min(y) + 0.05)")
    w("    }")
    w("")
    w("    #[test]")
    w("    fn keys_round_trip_and_names_are_dutch() {")
    w("        for theme in ThemeId::ALL {")
    w("            assert_eq!(ThemeId::from_key(theme.key()), Some(theme));")
    w("            let json = serde_json::to_string(&theme).unwrap();")
    w('            assert_eq!(json, format!("\\"{}\\"", theme.key()));')
    w("        }")
    w('        assert_eq!(ThemeId::default().name(), "Licht");')
    w("    }")
    w("")
    w("    #[test]")
    w("    fn body_text_meets_its_minimum_in_every_theme_and_setting() {")
    w("        for theme in ThemeId::ALL {")
    w("            let t = theme.tokens();")
    w("            let min = if t.high_contrast { 7.0 } else { 4.5 };")
    w("            for ws in WorkspaceSetting::ALL {")
    w("                for sb in StatusbarSetting::ALL {")
    w("                    let c = t.palette(ws, sb);")
    w("                    assert!(contrast(c.text, c.panel) >= min, \"{theme} text\");")
    w("                    assert!(contrast(c.workspace_text, c.workspace) >= min, \"{theme} {ws:?} workspace\");")
    w("                    assert!(contrast(t.workspace_accent_text(ws), c.workspace) >= 4.5, \"{theme} {ws:?} accent\");")
    w("                    assert!(contrast(c.statusbar_text, c.statusbar) >= 4.5, \"{theme} {sb:?} statusbar\");")
    w("                    assert!(contrast(c.text_on_accent, c.accent) >= 4.5, \"{theme} primary button\");")
    w("                }")
    w("            }")
    w("        }")
    w("    }")
    w("")
    w("    #[test]")
    w("    fn high_contrast_ignores_settings() {")
    w("        let t = HIGH_CONTRAST_DARK;")
    w("        assert_eq!(t.palette(WorkspaceSetting::Light, StatusbarSetting::Dark), t.color);")
    w("        assert!(t.selection_outline && t.disabled_dashed);")
    w("        assert!(Shadows::drop_shadow(t.shadow.panel).is_none());")
    w("        assert!(Shadows::drop_shadow(LIGHT.shadow.dialog).is_some());")
    w("    }")
    w("}")
    return "\n".join(o) + "\n"


def build_css(t):
    themes = t["themes"]
    ws = t["workspace-setting"]["options"]
    sb = t["statusbar-setting"]["options"]
    o = []
    w = o.append
    w("/* OpenAEC UI design tokens " + t["meta"]["version"] + " for web apps.")
    w(" * Generated by scripts/generate_tokens_04.py from design/ontwerp-0.4/tokens-0.4.json.")
    w(" * Do not edit by hand. Use: <html data-oa-theme=\"dark\" data-oa-workspace=\"theme\" data-oa-statusbar=\"theme\">")
    w(" * Themes: " + ", ".join(themes) + ". Workspace: theme, light, dark. Statusbar: theme, dark. */")
    w(":root {")
    for k, v in t["font"]["family"].items():
        fallback = "monospace" if k == "mono" else "system-ui, sans-serif"
        w(f'  --oa-font-{k}: "{v}", {fallback};')
    for k, v in t["font"]["size"].items():
        w(f"  --oa-size-{k}: {v}px;")
    for k, v in t["font"]["weight"].items():
        w(f"  --oa-weight-{k}: {v};")
    for k, v in t["font"]["letter-spacing"].items():
        w(f"  --oa-letter-spacing-{k}: {v};")
    for k, v in t["space"].items():
        w(f"  --oa-space-{k}: {v}px;")
    for k, v in t["radius"].items():
        w(f"  --oa-radius-{k}: {v}px;")
    for k, v in t["shell"].items():
        w(f"  --oa-shell-{k}: {v}px;")
    for k, v in t["brand"].items():
        w(f"  --oa-brand-{k}: {v};")
    w("}")
    for i, (k, th) in enumerate(themes.items()):
        sel = f':root, [data-oa-theme="{k}"]' if i == 0 else f'[data-oa-theme="{k}"]'
        w(sel + " {")
        w(f"  color-scheme: {th['kind']};")
        for key, v in th["color"].items():
            w(f"  --oa-{key}: {v};")
        w(f"  --oa-workspace-accent-text: {th['color']['accent-text']};")
        for s in ("panel", "popup", "dialog"):
            w(f"  --oa-shadow-{s}: {th['shadow'][s]};")
        w(f"  --oa-overlay: {th['overlay']};")
        w("}")
    w("/* Werkruimte and Statusbalk settings; High contrast ignores them. */")
    for k, th in themes.items():
        if th.get("high-contrast"):
            continue
        for opt in ("light", "dark"):
            v = ws[opt]
            other_kind = (luminance(v["workspace"]) > 0.5) != (th["kind"] == "light")
            accent = themes["light" if opt == "light" else "dark"]["color"]["accent-text"] if other_kind else th["color"]["accent-text"]
            w(f'[data-oa-theme="{k}"][data-oa-workspace="{opt}"] {{ --oa-workspace: {v["workspace"]}; '
              f'--oa-workspace-text: {v["workspace-text"]}; --oa-workspace-accent-text: {accent}; }}')
        w(f'[data-oa-theme="{k}"][data-oa-statusbar="dark"] {{ --oa-statusbar: {sb["dark"]["statusbar"]}; '
          f'--oa-statusbar-text: {sb["dark"]["statusbar-text"]}; }}')
    return "\n".join(o) + "\n"


def main():
    t = json.loads(SRC.read_text(encoding="utf-8"))
    problems, rows = evaluate(t)
    if problems:
        print("Tokens halen het contrast niet:\n- " + "\n- ".join(problems))
        return 1
    outputs = {RUST: build_rust(t), CSS: build_css(t)}
    check = "--check" in sys.argv[1:]
    stale = []
    for path, text in outputs.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != text:
            stale.append(path.relative_to(ROOT).as_posix())
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8", newline="\n")
    n = len(next(iter(t["themes"].values()))["color"])
    if check:
        if stale:
            print("Verouderd, draai scripts/generate_tokens_04.py: " + ", ".join(stale))
            return 1
        print(f"Tokens {t['meta']['version']}: Rust en CSS zijn actueel ({len(t['themes'])} thema's, {n} kleurrollen)")
        return 0
    print(f"Tokens {t['meta']['version']}: {len(t['themes'])} thema's, {n} kleurrollen, {len(rows)} kleurparen getoetst; "
          f"bijgewerkt: {', '.join(stale) or 'niets'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
