#!/usr/bin/env python3
"""Embed review-stage domain SVGs in the native Style Repo binary only."""

import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
drafts = json.loads((root / "design/domain-icon-drafts.json").read_text())
output = root / "src/bin/style_repo/domain_drafts.rs"
lines = ["// Generated by scripts/generate_domain_rust_index.py; review assets, not the public UI API.", "pub const ALL: [(&str, &[u8]); 109] = ["]
for draft in drafts:
    path = draft["file"]
    assert (root / "design" / path).is_file()
    lines.append(f'    ("{draft["id"]}", include_bytes!("../../../design/{path}")),')
lines += ["];", "", "pub fn get(id: &str) -> Option<&'static [u8]> {", "    ALL.iter().find(|(key, _)| *key == id).map(|(_, bytes)| *bytes)", "}"]
output.write_text("\n".join(lines) + "\n")
print(f"Indexed {len(drafts)} review icons for the native Style Repo")
