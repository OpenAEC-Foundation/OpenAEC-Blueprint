#!/usr/bin/env python3
"""Generate the `openaec-icons` crate from Codex's B2 icon export.

Sources:
  design/icon-set-b2/manifest.json                   ids, Dutch labels, groups, apps
  design/icon-set-b2/library-lossless/manifest.json  SVGZ files and hashes
Writes:
  crates/openaec-icons/assets/{16,24}/<id>.svgz      byte copies of the export
  crates/openaec-icons/src/generated.rs              the typed `Icon` list
  crates/openaec-icons/Cargo.toml                    one feature per app

Every icon is compiled in only when a feature of one of its apps is on, so an
app carries just its own icons. Run with --check to verify without writing.
"""

import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
B2 = ROOT / "design/icon-set-b2"
EXPORT = B2 / "library-lossless"
CRATE = ROOT / "crates/openaec-icons"

# App names in the B2 manifest -> crate features.
FEATURES = {
    "Calc": "calc", "Calculations": "calculations", "PDF": "pdf", "Planner": "planner",
    "Energy": "energy", "Heatloss": "heatloss", "Geotechniek": "geotechniek", "Pointcloud": "pointcloud",
    "Reports": "reports", "Workspace Composer": "composer", "BIM Validator": "validator", "Frame": "frame",
    "Pile Plan": "pile-plan", "Field": "field", "Speech": "speech", "Installer": "installer",
}


def variant(icon_id):
    parts = re.split(r"[.\-_]", icon_id)
    name = "".join(p[:1].upper() + p[1:] for p in parts if p)
    return name if name[0].isalpha() else "I" + name


def rust_str(s):
    return json.dumps(s, ensure_ascii=False)


def main():
    check = "--check" in sys.argv[1:]
    design = {i["id"]: i for i in json.loads((B2 / "manifest.json").read_text(encoding="utf-8"))["icons"]}
    export = json.loads((EXPORT / "manifest.json").read_text(encoding="utf-8"))
    icons = sorted(export["icons"], key=lambda i: i["id"])
    names = [variant(i["id"]) for i in icons]
    assert len(set(names)) == len(names), "two icon ids give the same Rust name"

    problems, writes = [], {}
    # Assets: exact byte copies, verified against the export's hashes.
    for icon in icons:
        for size, asset in icon["assets"].items():
            src = EXPORT / asset["path"]
            data = src.read_bytes()
            if hashlib.sha256(data).hexdigest() != asset["compressed_sha256"]:
                problems.append(f"export hash differs: {asset['path']}")
            writes[CRATE / "assets" / size / f"{icon['id']}.svgz"] = data

    entries = []
    for icon, name in zip(icons, names):
        meta = design.get(icon["id"], {})
        apps = sorted({FEATURES[a] for a in meta.get("candidate_apps") or [] if a in FEATURES})
        if not apps:
            problems.append(f"no app for {icon['id']}")
        cfg = "#[cfg(any(" + ", ".join(f'feature = "{a}"' for a in apps) + "))]"
        entries.append((icon["id"], name, meta.get("label", icon.get("label", "")), meta.get("group", ""), cfg, apps))

    o = []
    w = o.append
    w("// Generated by scripts/generate_icon_crate.py from design/icon-set-b2 (B2 revision "
      f"{export['source_revision']}). Do not edit by hand.")
    w("use crate::Size;")
    w("")
    w("/// The B2 icons. A variant exists only when a feature of one of its apps is on.")
    w("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]")
    w("#[non_exhaustive]")
    w("pub enum Icon {")
    for icon_id, name, label, group, cfg, apps in entries:
        w(f"    /// {label} (`{icon_id}`); {', '.join(apps)}.")
        w(f"    {cfg}")
        w(f"    {name},")
    w("}")
    w("")
    w(f'/// B2 revision of these icons.\npub const REVISION: u32 = {export["source_revision"]};')
    w("")
    w("impl Icon {")
    w("    /// Every icon that the enabled features include.")
    w("    pub fn all() -> Vec<Icon> {")
    w("        #[allow(unused_mut)]")
    w("        let mut list = Vec::new();")
    for icon_id, name, label, group, cfg, apps in entries:
        w(f"        {cfg}")
        w(f"        list.push(Icon::{name});")
    w("        list")
    w("    }")
    w("")
    for fn, doc, idx in (("id", "Function id, such as `file.save`.", 0), ("label", "Dutch label.", 2), ("group", "Dutch group in the B2 set.", 3)):
        w(f"    /// {doc}")
        w(f"    pub fn {fn}(self) -> &'static str {{")
        w("        match self {")
        for e in entries:
            w(f"            {e[4]}")
            w(f"            Icon::{e[1]} => {rust_str(e[idx])},")
        w("        }")
        w("    }")
        w("")
    w("    /// The icon for a function id, if a feature includes it.")
    w("    pub fn from_id(id: &str) -> Option<Icon> {")
    w("        match id {")
    for e in entries:
        w(f"            {e[4]}")
        w(f"            {rust_str(e[0])} => Some(Icon::{e[1]}),")
    w("            _ => None,")
    w("        }")
    w("    }")
    w("")
    w("    /// The gzip-compressed SVG master for a size.")
    w("    pub fn svgz(self, size: Size) -> &'static [u8] {")
    w("        match (self, size) {")
    for e in entries:
        for size in ("16", "24"):
            w(f"            {e[4]}")
            w(f'            (Icon::{e[1]}, Size::S{size}) => include_bytes!(concat!(env!("CARGO_MANIFEST_DIR"), "/assets/{size}/{e[0]}.svgz")),')
    w("        }")
    w("    }")
    w("}")
    writes[CRATE / "src/generated.rs"] = ("\n".join(o) + "\n").encode("utf-8")

    all_features = sorted(set(FEATURES.values()))
    toml = f'''# Generated by scripts/generate_icon_crate.py. Do not edit by hand.
[package]
name = "openaec-icons"
version = "0.1.0"
edition = "2021"
description = "B2 icons of OpenAEC UI 0.4 as a typed list, one feature per app"
license = "LGPL-3.0-only"
readme = "README.md"
publish = false
include = ["src/**", "assets/**", "Cargo.toml", "README.md", "LICENSE.md"]

[features]
default = []
# Every icon of every app, for the Style Repo and its gallery.
all = [{", ".join(rust_str(f) for f in all_features)}]
''' + "".join(f'{f} = []\n' for f in all_features) + '''
[dependencies]
flate2 = "1"
'''
    writes[CRATE / "Cargo.toml"] = toml.encode("utf-8")

    stale = []
    for path, data in writes.items():
        if not path.exists() or path.read_bytes() != data:
            stale.append(path)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(data)
    if check:
        # Assets that are no longer in the export.
        for path in (CRATE / "assets").rglob("*.svgz") if (CRATE / "assets").exists() else []:
            if path not in writes:
                stale.append(path)
    elif (CRATE / "assets").exists():
        for path in list((CRATE / "assets").rglob("*.svgz")):
            if path not in writes:
                path.unlink()
    if problems:
        print("Problemen:\n- " + "\n- ".join(problems[:20]))
        return 1
    per_app = {f: sum(1 for e in entries if f in e[5]) for f in all_features}
    if check:
        if stale:
            print(f"Verouderd, draai scripts/generate_icon_crate.py: {len(stale)} bestanden, bijvoorbeeld {stale[0].relative_to(ROOT).as_posix()}")
            return 1
        print(f"openaec-icons is actueel: {len(entries)} iconen, B2-revisie {export['source_revision']}")
        return 0
    print(f"openaec-icons: {len(entries)} iconen x 2 maten, B2-revisie {export['source_revision']}, {len(stale)} bestanden bijgewerkt")
    print("Iconen per app: " + ", ".join(f"{k} {v}" for k, v in per_app.items()))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
