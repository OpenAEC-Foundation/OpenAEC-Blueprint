"""Regenerate canonical theme colors from the checked-in style-book snapshot."""
from pathlib import Path
import re,json
root=Path(__file__).resolve().parents[1]
css=(root/'assets/themes.css').read_text()
variants=['light','forge','openaec','blueprint','contrast']
data={}
for name in variants:
    body=re.search(r'\[data-theme="'+name+r'"\]\s*\{(.*?)\n\}',css,re.S).group(1)
    data[name]=dict(re.findall(r'--theme-([\w-]+):\s*([^;]+);',body))
colors={k for k,v in data['light'].items() if v.startswith(('#','rgba(','rgb('))}
assert all(colors <= set(d) for d in data.values())
def color(v):
    if v.startswith('#'):
        v=v[1:]; rgb=[int(v[i:i+2],16)/255 for i in (0,2,4)];a=1
    else:
        n=[float(x) for x in re.findall(r'[\d.]+',v)];rgb=[x/255 for x in n[:3]];a=n[3] if len(n)==4 else 1
    return 'Color { r: %.9f, g: %.9f, b: %.9f, a: %.9f }'%(*rgb,a)
out=['// Generated by scripts/generate_tokens.py; source: assets/themes.css.','use iced::Color;','#[derive(Debug, Clone, Copy)]','pub struct Tokens {']
for key in sorted(colors): out.append(f'    pub {key.replace("-","_")}: Color,')
out.append('}')
for name in variants:
    out.append(f'pub const {name.upper()}: Tokens = Tokens {{')
    for key in sorted(colors):out.append(f'    {key.replace("-","_")}: {color(data[name][key])},')
    out.append('};')
(root/'crates/openaec-ui/src/tokens.rs').write_text('\n'.join(out)+'\n')
(root/'assets/tokens.json').write_text(json.dumps(data,indent=2)+'\n')
print(len(colors),'color tokens per theme')
